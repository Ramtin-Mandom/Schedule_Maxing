#: Why a kept placement is kept (PlacementProblem.kept_as).
KEPT_HISTORY = "history"  # its execution started or finished: immutable history
KEPT_MANUAL = "manual"  # the user's manual intent (a deliberate move), until released
KEPT_EXISTING = "kept"  # an incremental generation keeps every valid saved placement


@dataclass(frozen=True)
class DayReservation:
    """One generated date's saved placements and which of them the generation keeps (and why)."""

    date: date_
    stored: list[ScheduledTask]
    #: Kept placement id -> KEPT_HISTORY / KEPT_MANUAL / KEPT_EXISTING.
    kept: dict[uuid.UUID, str]
    #: The kept placements' tasks (including deleted ones).
    kept_tasks: dict[uuid.UUID, Task]
    blocking: list[PlacementProblem]
    notices: list[PlacementProblem]


@dataclass(frozen=True)
class Reservations:
    """Everything a generation of `dates` keeps, computed from one read (see plan_reservations)."""

    dates: list[date_]
    days: dict[date_, DayReservation]
    #: Occurrence keys of the kept placements on the generated dates: never placed again by this run.
    kept_keys: dict[tuple, ScheduledTask]
    #: Range task id -> its occurrence's live placement outside the generated dates: left there, not placed again.
    elsewhere: dict[uuid.UUID, ScheduledTask]
    #: Digest of every record the plan was made from (placements, versions, manual intent, execution statuses):
    #: recomputed inside the write transaction; a difference refuses the save.
    token: str

    @property
    def blocking(self) -> list[PlacementProblem]:
        return [problem for day in self.dates for problem in self.days[day].blocking]

    def excluded_task_ids(self, tasks: TaskRegistry) -> set[uuid.UUID]:
        """Range tasks whose occurrence is kept on a generated date or live elsewhere."""
        excluded = set(self.elsewhere)
        for day in self.dates:
            for task_id in tasks.tasks:
                task = tasks.get(task_id)
                if task_occurrence_key(task, day) in self.kept_keys or task_occurrence_key(task, None) in self.kept_keys:
                    excluded.add(task_id)
        return excluded


def plan_reservations(
    service: PlanningService, inputs: SchedulingInputs, dates: list[date_], *, mode: GenerationMode
) -> Reservations:
    """
    What a generation of `dates` keeps (docs/execution-rescheduling.md,
    "Manual placements" and "Scope"):

        - every saved placement whose execution started or finished
          (HISTORY_PROTECTED_STATUSES) -- immutable history;
        - every placement carrying manual intent (preserved, or proven by a
          recorded reschedule lineage: PlanningService.preserved_placement_ids);
        - INCREMENTAL also every other saved placement that still fits;
        - and, outside the generated dates, every live placement of an
          occurrence the range plans: it stays where it is, and this run does
          not place that occurrence again (moving it is the explicit
          reschedule).

    Kept work is checked against the current inputs: a manual or incremental
    placement that no longer fits is a *blocking* problem (the generation
    writes nothing; remedies say what resolves it); history that no longer
    fits is a non-blocking notice -- it stays exactly as recorded.
    """
    tasks = inputs.planning_range.tasks
    days: dict[date_, DayReservation] = {}
    kept_keys: dict[tuple, ScheduledTask] = {}
    token_rows: list[list] = []
    for day in dates:
        stored = service.placements_for_date(day)
        statuses = service.placement_execution_statuses(placement.id for placement in stored)
        preserved = service.preserved_placement_ids(stored)
        kept: dict[uuid.UUID, str] = {}
        for placement in stored:
            if statuses.get(placement.id) in HISTORY_PROTECTED_STATUSES:
                kept[placement.id] = KEPT_HISTORY
            elif placement.id in preserved:
                kept[placement.id] = KEPT_MANUAL
            elif mode == GenerationMode.INCREMENTAL:
                kept[placement.id] = KEPT_EXISTING
        kept_placements = [placement for placement in stored if placement.id in kept]
        kept_tasks = service.get_tasks_including_deleted(placement.task_id for placement in kept_placements)
        problems = _kept_problems(
            service, kept_placements, kept_tasks, inputs, day,
            full_check_ids={pid for pid, kind in kept.items() if kind != KEPT_HISTORY},
            kinds=kept, upcoming=set(tasks.tasks),
        )
        blocking = [problem for problem in problems if problem.blocking]
        notices = [problem for problem in problems if not problem.blocking]
        days[day] = DayReservation(day, stored, kept, dict(kept_tasks), blocking, notices)
        for placement in kept_placements:
            task = kept_tasks.get(placement.task_id)
            if task is not None:
                kept_keys.setdefault(occurrence_key(placement, task), placement)
        token_rows.extend(
            [str(p.id), p.version, p.planned_date.isoformat(), statuses.get(p.id), p.id in preserved] for p in stored
        )

    elsewhere = _placements_elsewhere(service, set(tasks.tasks), tasks, set(dates))
    token_rows.extend([str(task_id), str(p.id), p.version, p.planned_date.isoformat()]
                      for task_id, p in sorted(elsewhere.items(), key=lambda item: str(item[0])))
    elsewhere_statuses = service.placement_execution_statuses(p.id for p in elsewhere.values())
    token_rows.extend([str(pid), status] for pid, status in sorted(elsewhere_statuses.items(), key=lambda i: str(i[0])))
    token = hashlib.sha256(json.dumps(token_rows, sort_keys=True, default=str).encode("utf-8")).hexdigest()
    return Reservations(dates=list(dates), days=days, kept_keys=kept_keys, elsewhere=elsewhere, token=token)


def generate_from(
    service: PlanningService,
    allocation: AllocationResult,
    inputs: SchedulingInputs,
    dates: list[date_],
    *,
    mode: GenerationMode = GenerationMode.FULL,
    template: object = PROJECT_TEMPLATE,
    clock=None,
    preserve_on_empty: bool = False,
    reservations: Reservations | None = None,
    deadline: float | None = None,
) -> GenerationOutcome:
    """
    Generate `dates` (contiguous, inside the inputs' range) from a given
    allocation and save them (see generate). Kept work (plan_reservations)
    is reserved and never replaced; a blocking problem with it raises
    RegenerationRequiredError before anything is written.
    """
    if reservations is None:
        reservations = plan_reservations(service, inputs, dates, mode=mode)
    if reservations.blocking:
        raise RegenerationRequiredError(reservations.blocking)
    excluded = reservations.excluded_task_ids(inputs.planning_range.tasks)
    outputs: dict[date_, DayScheduleOutput] = {}
    expected: dict[uuid.UUID, int] = {}
    kept: dict[date_, list[uuid.UUID]] = {}
    for day in dates:
        _check_deadline(deadline)
        try:
            output = _generate_date(service, allocation, inputs, day, reservations=reservations, excluded=excluded,
                                    mode=mode)
        except MandatoryTaskSchedulingError as error:
            error.failed_date = day  # which date could not be generated (the error names only tasks)
            raise
        stored = reservations.days[day].stored
        outputs[day] = _with_category_snapshots(output, stored, service)
        expected.update({placement.id: placement.version for placement in stored})
        kept[day] = sorted(reservations.days[day].kept, key=str)
    order = _kept_order_problems(service, outputs, reservations, inputs)
    if order:
        raise RegenerationRequiredError(order)

    notices = {day: reservations.days[day].notices for day in dates if reservations.days[day].notices}
    if preserve_on_empty and expected and not any(output.placements for output in outputs.values()):
        # Nothing new to show and saved work would be wiped: keep the previous schedule untouched.
        return GenerationOutcome(status="nothing_placed", mode=mode, inputs=inputs, allocation=allocation,
                                 outputs=outputs, kept_ids=kept, notices=notices,
                                 kept_elsewhere=dict(reservations.elsewhere))

    _check_deadline(deadline)  # last chance: once the save starts it runs to its commit
    now = (clock or _utcnow)()
    provenance = GenerationProvenance(
        allocation_id=allocation.id, range_start=inputs.start_date, range_end=inputs.end_date,
        range_scope=inputs.scope.value, fingerprint=inputs.fingerprint, timezone=inputs.timezone_name,
        engine_modes={day: inputs.preferences_by_date[day].optimizer_mode for day in dates}, generated_at=now,
    )
    with service.transaction():
        # The write transaction re-reads every input: a change since generation started -- to any task, series,
        # block, preference or external dependency, to a placement's manual intent, to an execution's state, or to
        # a placement kept outside the generated dates -- refuses the save. Nothing is written in part.
        again = read_inputs(
            service, inputs.start_date, inputs.end_date, scope=inputs.scope, timezone_name=inputs.timezone_name,
            template=template, clock=clock,
        )
        if again.fingerprint != inputs.fingerprint:
            raise StaleInputsError(inputs.fingerprint, again.fingerprint)
        current = plan_reservations(service, inputs, dates, mode=mode)
        if current.token != reservations.token:
            raise StaleInputsError(
                reservations.token, current.token,
                "Saved placements, manual placements or execution states of these dates changed while the schedule "
                "was being generated. Nothing was saved; generate again.",
            )
        result = service.reschedule_range(
            dates[0], dates[-1], outputs, expected_versions=expected, provenance=provenance
        )
    return GenerationOutcome(
        status="generated", mode=mode, inputs=inputs, allocation=allocation, outputs=outputs, kept_ids=kept,
        reschedule=result, notices=notices, kept_elsewhere=dict(reservations.elsewhere),
        evaluations=evaluate_outputs(inputs, outputs, allocation),
    )


def evaluate_outputs(
    inputs: SchedulingInputs, outputs: Mapping[date_, DayScheduleOutput], allocation: AllocationResult | None = None
) -> dict[date_, DayEvaluation]:
    """Each date's objective under its mode (reporting only; nothing stored changes)."""
    evaluations = {}
    for day, output in outputs.items():
        preferences = inputs.preferences_by_date.get(day)
        if preferences is None:
            continue
        bonuses = _catch_up_bonuses(inputs, day, allocation)[0] if allocation is not None else None
        try:
            evaluations[day] = evaluate_day_output(output, preferences, task_bonuses=bonuses)
        except (UnsupportedSchedulingWindowError, AmbiguousLocalTimeError):
            continue
    return evaluations


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _check_deadline(deadline: float | None) -> None:
    if deadline is not None and time.monotonic() > deadline:
        raise GenerationLimitError("The schedule took too long to generate and was not saved. "
                                   "Try fewer dates or fewer tasks.")


def _with_category_snapshots(
    output: DayScheduleOutput, stored: list[ScheduledTask], service: PlanningService
) -> DayScheduleOutput:
    """
    The output as it will be saved: a placement the engine kept (same id)
    keeps its stored planning snapshot, origin and manual intent; a new one
    takes its task's snapshot now (category, name, tags, points, estimate,
    type) and is generated -- so what generation returns is exactly what is
    stored.
    """
    by_id = {placement.id: placement for placement in stored}
    new_tasks = {placement.task_id: output.tasks.get(placement.task_id)
                 for placement in output.placements if placement.id not in by_id}
    snapshots = service.placement_snapshots(new_tasks.values()) if new_tasks else {}
    placements = []
    for placement in output.placements:
        previous = by_id.get(placement.id)
        if previous is not None:
            placements.append(placement.model_copy(update={
                **{name: getattr(previous, name) for name in PLACEMENT_SNAPSHOT_FIELDS},
                "origin": previous.origin, "preserved": previous.preserved}))
        else:
            current = snapshots[placement.task_id]
            placements.append(placement.model_copy(update={
                **{name: getattr(placement, name) if getattr(placement, name) is not None else current[name]
                   for name in PLACEMENT_SNAPSHOT_FIELDS},
                "origin": placement.origin or PlacementOrigin.GENERATED}))
    return output.model_copy(update={"placements": placements})


def _stored_output(service: PlanningService, day: date_, state: DayFreshness, inputs: SchedulingInputs) -> DayScheduleOutput:
    """The saved result of a date, without unscheduled explanations (only their count was saved)."""
    tz = state.record.timezone if state.record is not None else inputs.timezone_name
    return service.stored_day_output(day, tz) or DayScheduleOutput(date=day, timezone=tz)


def _generate_date(
    service: PlanningService,
    allocation: AllocationResult,
    inputs: SchedulingInputs,
    day: date_,
    *,
    reservations: Reservations,
    excluded: set[uuid.UUID],
    mode: GenerationMode,
) -> DayScheduleOutput:
    """
    The date's new output: its kept placements exactly as they are, plus the
    day engine's placements of the date's other allocated work around them.
    FULL hands the engine the date's replaceable (generated, unprotected)
    placements as previous_result, so an identical placement keeps its id.
    """
    preferences = inputs.preferences_by_date[day]
    reservation = reservations.days[day]
    stored = reservation.stored
    tasks = inputs.planning_range.tasks
    blocks = inputs.planning_range.fixed_blocks_by_date[day]
    kept = [placement for placement in stored if placement.id in reservation.kept]
    kept_tasks = service.get_tasks_including_deleted(placement.task_id for placement in kept)

    satisfaction = dict(satisfaction_instants(inputs.external))
    for placement in [*kept, *reservations.kept_keys.values()]:
        satisfaction[placement.task_id] = (placement.planned_date, placement.planned_end)
    for task_id, placement in reservations.elsewhere.items():
        satisfaction[task_id] = (placement.planned_date, placement.planned_end)
    for task_id in excluded:
        task = tasks.get(task_id)
        if task is None:
            continue
        for key in (task_occurrence_key(task, day), task_occurrence_key(task, None)):
            if key in reservations.kept_keys:
                held = reservations.kept_keys[key]
                satisfaction[task_id] = (held.planned_date, held.planned_end)

    busy = _busy_blocks(kept, blocks, preferences, day)
    sub_allocation = allocation.model_copy(update={
        "assignments": {task_id: assigned for task_id, assigned in allocation.assignments.items() if task_id not in excluded}
    })
    previous = None
    if mode == GenerationMode.FULL:
        replaceable = [placement for placement in stored if placement.id not in reservation.kept]
        previous = DayScheduleOutput(
            date=day, timezone=preferences.timezone,
            tasks=service.get_tasks(placement.task_id for placement in replaceable),
            placements=replaceable, total_score=compute_total_score(replaceable),
        ) if replaceable else None
    bonuses, explanations = _catch_up_bonuses(inputs, day, sub_allocation)
    generated, _ = generate_selected_day(
        sub_allocation, day, tasks, {day: preferences}, {day: [*blocks, *busy]}, previous_result=previous,
        external_dependency_satisfaction=satisfaction, task_bonuses=bonuses,
    )
    if explanations:
        # A bounded explanation on each new Catch-Up placement (never the history itself; well under 4 KiB).
        generated = generated.model_copy(update={"placements": [
            placement.model_copy(update={"optimization_metadata": {
                **placement.optimization_metadata, "catch_up": explanations[placement.task_id]}})
            if placement.task_id in explanations else placement
            for placement in generated.placements
        ]})

    registry = TaskRegistry(tasks={**generated.tasks.tasks, **{p.task_id: kept_tasks[p.task_id] for p in kept}})
    placements = [*kept, *generated.placements]
    return DayScheduleOutput(
        date=day, timezone=generated.timezone, fixed_blocks=list(blocks), tasks=registry, placements=placements,
        unscheduled=generated.unscheduled, total_score=compute_total_score(placements),
    )


def _busy_blocks(
    kept: list[ScheduledTask], blocks: list[FixedBlock], preferences, day: date_
) -> list[FixedBlock]:
    """
    Kept placements as busy time for the day engine: each kept interval,
    clipped to the date's window, minus fixed blocks and time already
    reserved. (Kept history may overlap a fixed block added later or another
    kept placement; it stays as recorded, and only its free part is reserved.)
    """
    try:
        window_start, window_end = preferences.to_local_day_window().to_utc_instants()
    except (UnsupportedSchedulingWindowError, AmbiguousLocalTimeError):
        return []
    taken = sorted((block.planned_start, block.planned_end) for block in blocks)
    busy: list[FixedBlock] = []
    for placement in sorted(kept, key=lambda item: (item.planned_start, str(item.id))):
        segments = [(max(placement.planned_start, window_start), min(placement.planned_end, window_end))]
        for start, end in taken:
            segments = [piece for seg_start, seg_end in segments for piece in (
                (seg_start, min(seg_end, start)), (max(seg_start, end), seg_end))]
            segments = [(seg_start, seg_end) for seg_start, seg_end in segments if seg_start < seg_end]
        for index, (start, end) in enumerate(segments):
            busy.append(FixedBlock(
                id=uuid.uuid5(_RESERVED_NAMESPACE, str(placement.id) if index == 0 else f"{placement.id}/{index}"),
                user_id=placement.user_id, label="(kept work)", category="reserved", planned_date=day,
                timezone=preferences.timezone, planned_start=start, planned_end=end,
            ))
            taken.append((start, end))
        taken.sort()
    return busy


def _kept_order_problems(
    service: PlanningService,
    outputs: Mapping[date_, DayScheduleOutput],
    reservations: Reservations,
    inputs: SchedulingInputs,
) -> list[PlacementProblem]:
    """
    A kept (manual or incremental) placement whose dependency is planned by
    this run must still come after it: the day engine treats kept work as
    busy time and cannot order around it, so the result is checked here and
    a violation blocks the whole generation (nothing is written).
    """
    range_ids = set(inputs.planning_range.tasks.tasks)
    dates = set(reservations.dates)
    problems: list[PlacementProblem] = []
    stored_dependencies: dict[uuid.UUID, list[ScheduledTask]] | None = None
    for day in reservations.dates:
        reservation = reservations.days[day]
        same_day = {placement.task_id: placement for placement in outputs[day].placements}
        for placement in reservation.stored:
            kept_as = reservation.kept.get(placement.id)
            task = reservation.kept_tasks.get(placement.task_id)
            if kept_as in (None, KEPT_HISTORY) or task is None or task.deleted_at is not None:
                continue
            for dependency in task.dependency_ids:
                if dependency not in range_ids:
                    continue  # judged up front (_kept_problems)
                if stored_dependencies is None:
                    wanted = {d for t in inputs.planning_range.tasks.tasks.values() for d in t.dependency_ids}
                    stored_dependencies = service.active_placements_for_tasks(wanted)
                others = [p for other_day, output in outputs.items() if other_day != day
                          for p in output.placements if p.task_id == dependency]
                others += [p for p in stored_dependencies.get(dependency, []) if p.planned_date not in dates]
                if not _dependency_done_by(dependency, placement, day, same_day, {dependency: others}, inputs.external):
                    problems.append(PlacementProblem(
                        placement.id, placement.task_id, day, "dependency_not_satisfied",
                        f"its dependency {dependency} would not finish before it.", kept_as=kept_as,
                        blocking=True, remedies=_remedies("dependency_not_satisfied", kept_as),
                    ))
                    break
    return problems


def _catch_up_bonuses(
    inputs: SchedulingInputs, day: date_, allocation: AllocationResult
) -> tuple[dict[uuid.UUID, float] | None, dict[uuid.UUID, dict]]:
    """The Catch-Up bonuses and explanations of the tasks allocated to `day` (none for other modes)."""
    preferences = inputs.preferences_by_date[day]
    if preferences.optimizer_mode != OptimizerMode.CATCH_UP or inputs.catch_up is None:
        return None, {}
    tasks = inputs.planning_range.tasks
    allocated = [tasks.get(task_id) for task_id, assigned in allocation.assignments.items()
                 if assigned == day and tasks.get(task_id) is not None]
    weight = mode_weight(day_preferences_to_reward_settings(preferences).weight_importance)
    return catch_up_task_bonuses(inputs.catch_up, allocated, weight)


def _placements_elsewhere(
    service: PlanningService, task_ids: set[uuid.UUID], tasks: TaskRegistry, dates: set[date_]
) -> dict[uuid.UUID, ScheduledTask]:
    """
    For each task (in task_ids) whose occurrence already has a live placement
    on a date outside `dates`: the earliest such placement. An occurrence of a
    recurring series counts its own placements on any date and a legacy
    placement of its series on its original slot date
    (app/planning/occurrence.py). A series definition is never planned itself.
    """
    found: dict[uuid.UUID, ScheduledTask] = {}
    groups = {task_id: list(group) for task_id, group in service.active_placements_for_tasks(task_ids).items()}
    occurrences = {task_id: tasks.get(task_id) for task_id in task_ids
                   if tasks.get(task_id) is not None and tasks.get(task_id).is_occurrence}
    legacy = service.active_placements_for_tasks({task.series_id for task in occurrences.values()})
    for task_id, task in occurrences.items():
        groups.setdefault(task_id, []).extend(
            placement for placement in legacy.get(task.series_id, []) if placement.planned_date == task.occurrence_slot
        )
    for task_id, group in groups.items():
        task = tasks.get(task_id)
        if task is None or task.recurrence is not None:
            continue
        for placement in sorted(group, key=lambda p: (p.planned_date, p.planned_start, str(p.id))):
            if placement.planned_date not in dates:
                found.setdefault(task_id, placement)
    return found


def _minutes(start: datetime, end: datetime) -> float:
    return (end - start).total_seconds() / 60


#: What resolves a kept-placement problem (PlacementProblem.remedies).
_CONSTRAINT_REASONS = frozenset({
    "outside_day_window", "overlaps_fixed_block", "required_date_changed", "duration_changed", "deadline_missed",
    "engine_mode_changed", "dependency_not_satisfied", "unsupported_day_window",
})


def _remedies(reason: str, kept_as: str) -> tuple[str, ...]:
    if kept_as == KEPT_HISTORY:
        return ()  # history is never changed; nothing to resolve
    remedies: list[str] = []
    if reason in _CONSTRAINT_REASONS:
        remedies.append("edit_constraint")
    if reason == "task_out_of_range":
        remedies.append("choose_another_range")
    if reason != "task_deleted":
        remedies.append("move")
    if kept_as == KEPT_MANUAL:
        remedies.append("release_manual_intent")
    if kept_as == KEPT_EXISTING:
        remedies.append("regenerate_full")
    return tuple(remedies)


def _kept_problems(
    service: PlanningService,
    kept: list[ScheduledTask],
    kept_tasks: Mapping[uuid.UUID, Task],
    inputs: SchedulingInputs,
    day: date_,
    *,
    full_check_ids: set[uuid.UUID],
    kinds: Mapping[uuid.UUID, str] | None = None,
    upcoming: set[uuid.UUID] = frozenset(),
) -> list[PlacementProblem]:
    """
    Why kept placements no longer fit the current inputs. Every kept placement
    is checked for reservability (inside the date's window, clear of fixed
    blocks and of each other); those in `full_check_ids` must also still be a
    valid placement of their task (required date, duration, deadline, engine
    mode, dependencies). `kinds` says why each is kept: a history placement's
    problems never block (it stays as recorded); others block. A dependency
    among `upcoming` (scheduled by this run) is left to the day engine.
    """
    kinds = kinds or {}
    preferences = inputs.preferences_by_date[day]
    blocks = inputs.planning_range.fixed_blocks_by_date[day]
    problems: list[PlacementProblem] = []

    def problem(placement: ScheduledTask, reason: str, explanation: str) -> None:
        kept_as = kinds.get(placement.id, KEPT_EXISTING)
        problems.append(PlacementProblem(
            placement.id, placement.task_id, day, reason, explanation, kept_as=kept_as,
            blocking=kept_as != KEPT_HISTORY, remedies=_remedies(reason, kept_as),
        ))

    try:
        window_start, window_end = preferences.to_local_day_window().to_utc_instants()
    except (UnsupportedSchedulingWindowError, AmbiguousLocalTimeError) as error:
        for placement in kept:
            problem(placement, "unsupported_day_window", str(error))
        return problems

    in_range = inputs.planning_range.tasks
    dependency_ids = {dep for task in kept_tasks.values() for dep in task.dependency_ids}
    dependency_placements = service.active_placements_for_tasks(dependency_ids) if full_check_ids else {}
    kept_by_task = {placement.task_id: placement for placement in kept}

    for placement in sorted(kept, key=lambda item: (item.planned_start, str(item.id))):
        task = kept_tasks.get(placement.task_id)
        if placement.planned_start < window_start or placement.planned_end > window_end:
            problem(placement, "outside_day_window", "it lies outside this date's day window.")
        clash = next(
            (b for b in blocks if placement.planned_start < b.planned_end and b.planned_start < placement.planned_end), None
        )
        if clash is not None:
            problem(placement, "overlaps_fixed_block", f"it overlaps the fixed block {clash.label!r}.")
        other = next((o for o in kept if o.id != placement.id
                      and placement.planned_start < o.planned_end and o.planned_start < placement.planned_end), None)
        if other is not None:
            problem(placement, "overlaps_placement", f"it overlaps the saved placement {other.id}.")
        if placement.id not in full_check_ids:
            continue
        if task is None or task.deleted_at is not None:
            problem(placement, "task_deleted", "its task was deleted.")
            continue
        if task.id not in in_range and not task.is_series:
            # (A legacy placement of a series definition is that date's occurrence; the definition itself is
            # never part of a range's tasks.)
            problem(placement, "task_out_of_range", "its task is no longer planned in this range.")
            continue
        if task.required_date is not None and task.required_date != day:
            problem(placement, "required_date_changed", f"its task must now happen on {task.required_date}.")
        if round(_minutes(placement.planned_start, placement.planned_end)) != task.estimated_duration_minutes:
            problem(placement, "duration_changed", f"its task now takes {task.estimated_duration_minutes} minutes.")
        if task.deadline is not None and placement.planned_end > task.deadline:
            problem(placement, "deadline_missed", f"it would end after the task's deadline ({task.deadline.isoformat()}).")
        if (
            preferences.optimizer_mode == OptimizerMode.ADHD_FRIENDLY
            and task.estimated_duration_minutes > 30
            and _local_minute(placement.planned_start, preferences.timezone) % 15 != 0
        ):
            problem(placement, "engine_mode_changed",
                    "the adhd_friendly engine starts tasks over 30 minutes on quarter hours only.")
        for dependency in task.dependency_ids:
            if dependency in upcoming and dependency not in kept_by_task:
                continue  # scheduled (or kept elsewhere) by this run: the engine orders it before what depends on it
            if not _dependency_done_by(dependency, placement, day, kept_by_task, dependency_placements, inputs.external):
                problem(placement, "dependency_not_satisfied", f"its dependency {dependency} no longer finishes before it.")
                break
    return problems


def _local_minute(instant: datetime, tz_name: str) -> int:
    local = instant.astimezone(ZoneInfo(tz_name))
    return local.hour * 60 + local.minute


def _dependency_done_by(
    dependency: uuid.UUID,
    placement: ScheduledTask,
    day: date_,
    kept_by_task: Mapping[uuid.UUID, ScheduledTask],
    dependency_placements: Mapping[uuid.UUID, list[ScheduledTask]],
    external: Mapping[uuid.UUID, ExternalDependency],
) -> bool:
    same_day = kept_by_task.get(dependency)
    if same_day is not None:
        return same_day.planned_end <= placement.planned_start
    if any(other.planned_date < day for other in dependency_placements.get(dependency, [])):
        return True
    resolved = external.get(dependency)
    if resolved is not None and resolved.satisfied:
        return resolved.satisfied_date < day or resolved.satisfied_at <= placement.planned_start
    return False


