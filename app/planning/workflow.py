@dataclass(frozen=True)
class PlacementProblem:
    """
    Why a placement that would be kept (or a move's destination) no longer
    fits the current inputs. `kept_as` says why it is kept ("history",
    "manual", "kept"; "destination" for a move); `blocking` whether
    generation refuses to write until it is resolved (history never blocks:
    it stays exactly as recorded); `remedies` what resolves it --
    "edit_constraint", "move" (the explicit reschedule, if legal),
    "release_manual_intent", "choose_another_range", "regenerate_full".
    """

    placement_id: uuid.UUID
    task_id: uuid.UUID
    date: date_
    reason: str
    explanation: str
    kept_as: str = "kept"
    blocking: bool = True
    remedies: tuple[str, ...] = ()


@dataclass(frozen=True)
class GenerationOutcome:
    #: "generated", "already_current" or (preserve_on_empty) "nothing_placed"; the latter two wrote nothing.
    status: str
    mode: GenerationMode
    inputs: SchedulingInputs
    allocation: AllocationResult
    #: Per generated date: the saved result (for already_current: the stored placements, no unscheduled reasons).
    outputs: dict[date_, DayScheduleOutput]
    #: Per generated date: the placements kept exactly as they were (incremental, or protected history).
    kept_ids: dict[date_, list[uuid.UUID]] = field(default_factory=dict)
    reschedule: RescheduleResult | None = None
    #: The recurrence expansion of the allocation range that ran first (docs/recurrence.md).
    expansion: ExpansionResult | None = None
    #: Per generated date: non-blocking problems of kept history (it stays exactly as recorded).
    notices: dict[date_, list[PlacementProblem]] = field(default_factory=dict)
    #: Range task id -> its occurrence's placement outside the generated dates, left there (not placed again).
    kept_elsewhere: dict[uuid.UUID, ScheduledTask] = field(default_factory=dict)
    #: Per generated date: its objective under its mode, recomputed (app/optimizer.evaluate_day_output).
    evaluations: dict[date_, DayEvaluation] = field(default_factory=dict)


def range_dates(start_date: date_, end_date: date_) -> list[date_]:
    return [start_date + timedelta(days=offset) for offset in range((end_date - start_date).days + 1)]


def check_range(start_date: date_, end_date: date_) -> None:
    if end_date < start_date:
        raise ScopeError(f"end_date {end_date} is before start_date {start_date}.")
    if (end_date - start_date).days + 1 > MAX_RANGE_DAYS:
        raise ScopeError(f"a range may span at most {MAX_RANGE_DAYS} days.")


def expand_range(service: PlanningService, start_date: date_, end_date: date_, *, clock=None) -> ExpansionResult:
    """
    Materialize the recurring occurrences of an allocation range before its
    inputs are read (app/planning/series.py): bounded by the range limit and
    the expansion budget, idempotent, in its own transaction. Every persisted
    generation path (generate, preview_allocation, the desktop's range and
    allocation runs) calls it first, so allocation always sees the concrete
    occurrences and never a series definition.
    """
    check_range(start_date, end_date)
    return expand_occurrences(service, start_date, end_date, clock=clock)


