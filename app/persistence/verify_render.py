def _connect(settings, backend_factory, report: Report):
    facts = settings.describe()
    where = ("local server (TLS not required)" if facts["local_server"] == "True"
             else f"remote server over TLS (sslmode={facts['tls']})")
    report.facts["database"] = f"DATABASE_URL from the {settings.source}; {where}"
    backend = backend_factory(settings)
    current, head = backend.schema_revision()
    report.done("connection")
    report.facts["schema"] = f"revision {current or 'none'} (this version needs {head})"
    return backend, current, head


def _account(backend, args, password_source, report: Report):
    from app.persistence.errors import InvalidCredentialsError

    exists = backend.account_exists(email=args.email)
    password = password_source(f"Password for {args.email.strip()}: ")
    if not password:
        raise VerificationError("No password was entered.")
    if not exists:
        if password_source("Repeat the password for the new account: ") != password:
            raise VerificationError("The two passwords differ; nothing was created.")
        backend.register(email=args.email, password=password, display_name=args.display_name)
    try:
        account = backend.sign_in(email=args.email, password=password)
    except InvalidCredentialsError:
        raise VerificationError("The password does not match the existing account; nothing was changed "
                                "(an existing password is never reset).") from None
    identity = account.identity
    report.facts["account"] = (f"{identity.display_name or '(no display name)'} <{identity.email}> "
                               f"({'created' if not exists else 'existing'}, password verified)")
    if identity.display_name != args.display_name.strip():
        report.facts["account"] += "; its stored display name differs and was left unchanged"
    report.done("account", "created" if not exists else "existing")
    return account, password


def _check_date_is_free(planning, seed: Seed) -> None:
    """Refuse a date holding other records of the user: generation there would reschedule them."""
    seed_ids = {task.id for task in seed.tasks} | {block.id for block in seed.fixed_blocks}
    others = [task for task in planning.tasks_planned_in_range(seed.day, seed.day, timezone_name=seed.timezone)
              if task.id not in seed_ids]
    others += [block for block in planning.fixed_blocks_for_date(seed.day) if block.id not in seed_ids]
    if others:
        raise SeedConflict(
            f"{seed.day.isoformat()} already holds {len(others)} other task(s)/fixed block(s) of this account (undated "
            "tasks count, since generation would schedule them). Nothing was written; choose another --anchor-date.")


def _apply_seed(planning, seed: Seed) -> int:
    """Create missing seed records in one transaction; identical ones stay; changed ones are a conflict. Returns created."""
    with planning.transaction():  # the user's lock: concurrent runs serialize here
        _check_date_is_free(planning, seed)
        stored_tasks = planning.get_tasks_including_deleted([task.id for task in seed.tasks])
        conflicts, missing_tasks, missing_blocks = [], [], []
        for task in seed.tasks:
            stored = stored_tasks.get(task.id)
            if stored is None:
                missing_tasks.append(task)
            elif stored.deleted_at is not None or _content(stored, TASK_CONTENT) != _content(task, TASK_CONTENT):
                conflicts.append(f"task {task.name!r} was {'deleted' if stored.deleted_at else 'edited'}")
        for block in seed.fixed_blocks:
            stored = planning.get_fixed_block(block.id, include_deleted=True)
            if stored is None:
                missing_blocks.append(block)
            elif stored.deleted_at is not None or _content(stored, BLOCK_CONTENT) != _content(block, BLOCK_CONTENT):
                conflicts.append(f"fixed block {block.label!r} was {'deleted' if stored.deleted_at else 'edited'}")
        if conflicts:
            raise SeedConflict("The seeded records changed since they were created (" + "; ".join(conflicts) +
                               "). They were left as they are; nothing was overwritten.")
        if missing_tasks:
            planning.create_tasks(missing_tasks)
        for block in missing_blocks:
            planning.create_fixed_block(block)
        return len(missing_tasks) + len(missing_blocks)


def seed_preferences():
    from app.planning.preferences import OptimizerMode, PreferenceOverrides

    return PreferenceOverrides(optimizer_mode=OptimizerMode.PRECISE_GREEDY, category_multipliers={"study": 1.0})


def _apply_preference(planning, day: date) -> str:
    wanted = seed_preferences()
    with planning.transaction():
        stored = planning.date_preferences(day)
        if stored is None:
            planning.save_date_preferences(day, wanted)
            return "created"
        if stored.overrides != wanted:
            raise SeedConflict(f"{day.isoformat()} already has a preference layer that differs from the sample's; it "
                               "was left unchanged.")
        return "already present"


def _generate(planning, seed: Seed) -> str:
    from app.planning import workflow
    from app.planning.application import RangeScope

    outcome = workflow.generate(planning, range_start=seed.day, range_end=seed.day, timezone_name=seed.timezone,
                                scope=RangeScope.PLANNED)
    return outcome.status


def _study_execution(account, planning, seed: Seed):
    study = next(task for task in seed.tasks if task.name == "Study Session")
    placement = next((p for p in planning.placements_for_date(seed.day) if p.task_id == study.id), None)
    if placement is None:
        raise VerificationError("The Study Session was not placed, so no execution could be recorded for it.")
    return account.execution_service().get_or_create_canonical_execution(planning.get_task(study.id), placement)


def _change_count(backend, user_id: uuid.UUID) -> int:
    from sqlalchemy import func, select

    from backend import models

    with backend.operation() as session:
        return session.scalar(select(func.count()).select_from(models.ChangeLogEntry)
                              .where(models.ChangeLogEntry.user_id == user_id))


def _read_back(account, seed: Seed, execution_id: str) -> dict[str, int]:
    """Everything the run stored, re-read through the public services of a fresh connection, and checked."""
    from app.planning import workflow

    planning = account.planning_service()
    owner = account.user_id
    tasks = planning.get_tasks([task.id for task in seed.tasks]).tasks
    if set(tasks) != {task.id for task in seed.tasks}:
        raise VerificationError("Not every seeded task could be read back.")
    for task in seed.tasks:
        stored = tasks[task.id]
        if stored.user_id != owner or _content(stored, TASK_CONTENT) != _content(task, TASK_CONTENT):
            raise VerificationError(f"The task {task.name!r} read back with different values or owner.")
    blocks = {block.id: block for block in planning.fixed_blocks_for_date(seed.day)}
    for block in seed.fixed_blocks:
        stored = blocks.get(block.id)
        if stored is None or stored.user_id != owner or _content(stored, BLOCK_CONTENT) != _content(block, BLOCK_CONTENT):
            raise VerificationError(f"The fixed block {block.label!r} read back missing or different.")
    placements = planning.placements_for_date(seed.day)
    by_task = {task.id: task for task in seed.tasks}
    intervals = [(block.planned_start, block.planned_end) for block in seed.fixed_blocks]
    for placement in placements:
        task = by_task.get(placement.task_id)
        if task is None or placement.user_id != owner or placement.planned_date != seed.day:
            raise VerificationError("A placement on the seed date does not belong to the seeded tasks.")
        minutes = (placement.planned_end - placement.planned_start).total_seconds() / 60
        if minutes != task.estimated_duration_minutes:
            raise VerificationError(f"The placement of {task.name!r} does not last its estimated duration.")
        for start, end in intervals:
            if placement.planned_start < end and start < placement.planned_end:
                raise VerificationError(f"The placement of {task.name!r} overlaps a fixed block or another task.")
        intervals.append((placement.planned_start, placement.planned_end))
    for task in seed.tasks:  # dependencies are respected (the dependency fixture's chain)
        own = next((p for p in placements if p.task_id == task.id), None)
        for dependency in task.dependency_ids:
            before = next((p for p in placements if p.task_id == dependency), None)
            if own is not None and (before is None or before.planned_end > own.planned_start):
                raise VerificationError(f"{task.name!r} is placed before a task it depends on.")
    freshness = workflow.day_freshness(planning, [seed.day], seed.timezone)[seed.day]
    if freshness.status != workflow.Freshness.CURRENT:
        raise VerificationError(f"The seed date's schedule is not current after reopening ({freshness.status.value}).")
    layer = planning.date_preferences(seed.day)
    if layer is None or layer.overrides != seed_preferences():
        raise VerificationError("The sample's preference layer did not read back identically.")
    counts = {"tasks": len(tasks), "fixed_blocks": len(seed.fixed_blocks), "placements": len(placements)}
    if execution_id:
        executions = account.execution_service()
        execution = executions.get_execution(execution_id)
        if execution.user_id != owner or execution.status.value != "scheduled" or executions.list_sessions(execution_id):
            raise VerificationError("The sample execution read back with another owner, status or invented sessions.")
        counts["executions"] = 1
    return counts


def _password_scope(backend, account, password: str, capture: _Capture, seeds: list[Seed]) -> str:
    """
    Scope, stated in the output: the account's stored credential is a valid
    Argon2id hash that verifies the password; the schema has no plaintext
    credential column; the records and change-log snapshots written for the
    seeded ids, and every log message of this run, do not contain the
    password. The comparison happens here in Python -- the password is never
    sent in a search statement -- and this is not a database-wide audit.
    """
    from sqlalchemy import inspect as sa_inspect
    from sqlalchemy import select

    from backend import models, snapshots
    from backend.passwords import verify_password

    with backend.operation() as session:
        stored_hash = session.scalar(select(models.User.password_hash).where(models.User.id == account.user_id))
        columns = {(table, column["name"]) for table in sa_inspect(session.connection()).get_table_names()
                   for column in sa_inspect(session.connection()).get_columns(table)}
        entity_ids = [record.id for seed in seeds for record in (*seed.tasks, *seed.fixed_blocks)]
        entries = list(session.scalars(select(models.ChangeLogEntry).where(
            models.ChangeLogEntry.user_id == account.user_id, models.ChangeLogEntry.entity_id.in_(entity_ids))))
        written = [snapshots.decode(entry.revision) for entry in entries]
    if not stored_hash or not stored_hash.startswith("$argon2id$") or not verify_password(password, stored_hash):
        raise VerificationError("The stored credential is not a valid Argon2id hash of the password.")
    credential_columns = {pair for pair in columns if any(word in pair[1] for word in ("password", "secret", "token"))}
    if credential_columns - {("users", "password_hash"), ("browser_sessions", "token_hash"),
                             ("password_recovery_tokens", "token_hash"), ("refresh_credentials", "token_hash")}:
        raise VerificationError("The schema has a credential column that is not a hash.")
    texts = [repr(record) for record in written] + [repr(record.model_dump()) for seed in seeds
                                                     for record in (*seed.tasks, *seed.fixed_blocks)]
    if any(password in text for text in texts) or any(password in message for message in capture.messages):
        raise VerificationError("The password appeared in data or log output written by this run.")
    return (f"stored credential is an Argon2id hash that verifies; no plaintext credential column; password absent "
            f"from {len(written)} change-log snapshot(s) of the seeded records and {len(capture.messages)} log "
            "message(s) of this run (scope: this account and this run, not a database-wide audit)")


