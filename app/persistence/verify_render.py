def _date(value: str) -> date:
    try:
        return date.fromisoformat(value)
    except ValueError:
        raise argparse.ArgumentTypeError("use YYYY-MM-DD") from None


def _zone(value: str) -> str:
    from app.planning.time import validate_timezone

    try:
        validate_timezone(value)
    except ValueError:
        raise argparse.ArgumentTypeError("use an IANA time zone such as America/Vancouver") from None
    return value


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python -m app.persistence.verify_render",
                                description="Opt-in verification of direct PostgreSQL storage (see "
                                            "docs/render-direct-desktop.md). Prints a safe summary only.")
    p.add_argument("--env-file", metavar="PATH", help="read DATABASE_URL from this file (the environment still wins)")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check-only", action="store_true", help="connection, TLS and schema revision; writes nothing")
    mode.add_argument("--write-sample", action="store_true", help="the account and the idempotent sample (see above)")
    p.add_argument("--email", help="the account's email (required with --write-sample)")
    p.add_argument("--display-name", help="the display name of a new account (required with --write-sample)")
    p.add_argument("--anchor-date", type=_date, help="the date day 1 of the sample becomes (required with --write-sample)")
    p.add_argument("--timezone", type=_zone, help="the IANA time zone of the sample (required with --write-sample)")
    p.add_argument("--dependency-date", type=_date,
                   help="optional: also seed samples/inputs/dependency_chain_linear.csv on this (different) date")
    return p


def main(argv: list[str] | None = None, *, backend_factory: Callable | None = None,
         password_source: Callable[[str], str] = getpass.getpass, environ=None, out=print) -> int:
    args = parser().parse_args(argv)
    if args.write_sample:
        missing = [name for name in ("email", "display_name", "anchor_date", "timezone") if getattr(args, name) is None]
        if missing:
            parser().error("--write-sample needs " + ", ".join("--" + name.replace("_", "-") for name in missing))
        if args.dependency_date is not None and args.dependency_date == args.anchor_date:
            parser().error("--dependency-date must differ from --anchor-date")

    from app.persistence import load_direct_settings, open_direct_backend
    from app.persistence.errors import DirectPersistenceError

    try:
        settings = load_direct_settings(env_file=args.env_file, environ=environ)
    except DirectPersistenceError as error:
        out(f"Schedule Maxing direct-database verification: FAILURE\n  problem: {error}\n  (nothing was run)")
        return 2
    factory = backend_factory or (lambda direct_settings: open_direct_backend(direct_settings, check_schema=False))
    if args.check_only:
        report, code = check_only(settings, factory)
    else:
        report, code = write_sample(args, settings, factory, password_source)
    report.facts.setdefault("checked at", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    out("\n".join(report.lines()))
    return code


if __name__ == "__main__":
    sys.exit(main())
