@dataclass
class Report:
    mode: str
    steps: dict[str, str] = field(default_factory=lambda: {step: "not run" for step in STEPS})
    facts: dict[str, str] = field(default_factory=dict)
    problem: str | None = None

    def done(self, step: str, detail: str = "ok") -> None:
        self.steps[step] = detail

    def failed(self, step: str, message: str) -> None:
        self.steps[step] = "FAILED"
        self.problem = message

    @property
    def ok(self) -> bool:
        return self.problem is None

    def lines(self) -> list[str]:
        outcome = "SUCCESS" if self.ok else "FAILURE"
        lines = [f"Schedule Maxing direct-database verification ({self.mode}): {outcome}"]
        lines += [f"  {name}: {value}" for name, value in self.facts.items()]
        if self.problem:
            lines.append(f"  problem: {self.problem}")
        relevant = STEPS[:2] if self.mode == "check-only" else STEPS
        lines.append("  steps: " + ", ".join(f"{step} {self.steps[step]}" for step in relevant))
        return lines


def _safe(error: BaseException) -> str:
    from app.execution.errors import ExecutionError
    from app.persistence.errors import DirectPersistenceError
    from app.planning.errors import PlanningError

    if isinstance(error, (VerificationError, DirectPersistenceError, PlanningError, ExecutionError)):
        return str(error)
    try:
        from sqlalchemy.exc import SQLAlchemyError

        if isinstance(error, SQLAlchemyError):
            from app.persistence.direct import safe_database_error

            return str(safe_database_error(error))
    except ModuleNotFoundError:
        pass
    return f"an unexpected {type(error).__name__} occurred"


class _Capture(logging.Handler):
    """Collects every log message emitted while the command runs (for the password scope check)."""

    def __init__(self) -> None:
        super().__init__(logging.DEBUG)
        self.messages: list[str] = []

    def emit(self, record: logging.LogRecord) -> None:
        try:
            self.messages.append(record.getMessage())
        except Exception:  # noqa: BLE001 - a malformed record must not break the run
            pass


