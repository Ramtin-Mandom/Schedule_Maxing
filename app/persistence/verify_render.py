def check_only(settings, backend_factory) -> tuple[Report, int]:
    report = Report("check-only")
    backend = None
    try:
        backend, current, head = _connect(settings, backend_factory, report)
        if current != head:
            report.failed("schema", f"the schema is not current; after a backup run 'python -m backend.migrate "
                                    f"--env-file .env upgrade' (current {current or 'none'}, needed {head})")
            return report, 1
        report.done("schema", "current")
        return report, 0
    except Exception as error:  # noqa: BLE001 - reported safely
        report.failed(next(step for step in STEPS if report.steps[step] == "not run"), _safe(error))
        return report, 2
    finally:
        if backend is not None:
            backend.close()


def write_sample(args, settings, backend_factory, password_source) -> tuple[Report, int]:
    report = Report("write-sample")
    capture = _Capture()
    logging.getLogger().addHandler(capture)
    backend = account = password = None
    step = "connection"
    try:
        backend, current, head = _connect(settings, backend_factory, report)
        step = "schema"
        if current != head:
            raise VerificationError(f"the schema is not current (current {current or 'none'}, needed {head}); nothing "
                                    "was written. After a backup, run 'python -m backend.migrate --env-file .env upgrade'.")
        report.done("schema", "current")

        step = "account"
        account, password = _account(backend, args, password_source, report)
        planning = account.planning_service()

        step = "seed"
        seeds = [load_seed(MAIN_SAMPLE, user_id=account.user_id, day=args.anchor_date, timezone_name=args.timezone)]
        main = seeds[0]
        found = {"tasks": len(main.tasks), "fixed_blocks": len(main.fixed_blocks), "day_indexes": main.day_indexes,
                 "dependencies": main.dependency_count}
        if found != MAIN_EXPECTED:
            raise VerificationError("The main sample file no longer has the expected content (3 flexible tasks, "
                                    "4 fixed blocks, day 1, no dependencies); nothing was written.")
        if args.dependency_date is not None:
            seeds.append(load_seed(DEPENDENCY_SAMPLE, user_id=account.user_id, day=args.dependency_date,
                                   timezone_name=args.timezone))
        before = _change_count(backend, account.user_id)
        created = sum(_apply_seed(planning, seed) for seed in seeds)
        report.done("seed", f"{created} record(s) created" if created else "already seeded")
        report.facts["seed"] = f"{main.fixture} ({FIXTURE_VERSION}) on {main.day.isoformat()} in {main.timezone}"
        report.facts["dependencies"] = ("none in the main sample (not applicable)" + (
            f"; {seeds[1].fixture} on {seeds[1].day.isoformat()}: {seeds[1].dependency_count} dependencies"
            if len(seeds) > 1 else ""))

        step = "preference"
        report.done("preference", "; ".join(_apply_preference(planning, seed.day) for seed in seeds))

        step = "generation"
        report.done("generation", "; ".join(_generate(planning, seed) for seed in seeds))

        step = "execution"
        execution = _study_execution(account, planning, main)
        report.done("execution", f"{execution.status.value} (sample-derived, no work recorded)")
        written = _change_count(backend, account.user_id) - before
        report.facts["idempotence"] = ("nothing needed changing (0 new change-log entries)" if not written else
                                       f"{written} change(s) written; a repeated run writes none")

        step = "read-back"
        backend.close()  # a fresh Engine and session: nothing read back comes from this run's objects
        backend = backend_factory(settings)
        account = backend.sign_in(email=args.email, password=password)
        counts = [_read_back(account, seed, execution.id if seed is main else "") for seed in seeds]
        main_counts = counts[0]
        report.facts["records"] = (f"{main_counts['tasks']} tasks, {main_counts['fixed_blocks']} fixed blocks, "
                                   f"{main_counts['placements']} placements, {main_counts['executions']} execution "
                                   "(scheduled)")
        report.facts["reopened connection"] = "signed in again; ids, owner, values, placements and freshness verified"
        report.facts["preference and freshness"] = "date layer read back identically; the date is current"
        report.done("read-back")

        step = "password-scope"
        report.facts["password check"] = _password_scope(backend, account, password, capture, seeds)
        report.done("password-scope")
        return report, 0
    except Exception as error:  # noqa: BLE001 - reported safely; completed steps stay listed
        report.failed(step, _safe(error))
        return report, 1 if isinstance(error, SeedConflict) else 2
    finally:
        password = None  # drop the reference (Python cannot promise to erase the string from memory)
        logging.getLogger().removeHandler(capture)
        if account is not None:
            account.sign_out()
        if backend is not None:
            backend.close()


