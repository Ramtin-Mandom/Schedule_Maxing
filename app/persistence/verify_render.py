"""
app/persistence/verify_render.py

An explicit, opt-in verification of the direct PostgreSQL storage against a
real database (docs/render-direct-desktop.md). It never runs by itself:
importing this module does nothing, no test hook calls it, and every mode
must be chosen on the command line.

    python -m app.persistence.verify_render --env-file .env --check-only
    python -m app.persistence.verify_render --env-file .env --write-sample \\
        --email Ramtin1383.5@gmail.com --display-name Ramtin \\
        --anchor-date 2026-09-28 --timezone America/Vancouver [--dependency-date 2026-09-29]

--check-only    connection, TLS mode and schema revision. No DDL, no account,
                no writes. Exit 0 = current, 1 = schema not current, 2 = failure.

--write-sample  requires the schema at the current revision (migrate first,
                explicitly: `python -m backend.migrate --env-file .env upgrade`).
                1. The account: created if absent (the password is asked twice),
                   otherwise signed in with the supplied password -- a wrong
                   password stops everything; a password is never reset.
                2. samples/inputs/valid_single_day_basic.csv (3 flexible tasks, 4
                   fixed blocks, day 1, no dependencies -- asserted) converted by
                   the ordinary legacy importer onto --anchor-date in --timezone,
                   then given stable seed identities (uuid5 of fixture version,
                   user, date, timezone and CSV line), dependencies remapped.
                   Seeding is one transaction under the user's lock: missing
                   records are created; identical ones are left alone; edited or
                   deleted ones are reported as a conflict and nothing is
                   overwritten. A date that already holds other records of the
                   user is refused (nothing is replaced or reset).
                3. A neutral preference layer for that date (the precise engine,
                   study multiplier 1.0): created if absent, left if identical, a
                   conflict if the user's layer differs.
                4. The date's schedule, generated by the shared planning workflow
                   (an unchanged date is "already current": nothing is written).
                5. One scheduled execution for the sample's Study Session
                   placement (get-or-create; no work is invented).
                6. The session is closed and the engine disposed; a new one
                   signs in again and reads everything back through the public
                   services, checking ids, ownership, values, placement validity
                   and freshness.
                7. Password checks within a stated scope (see _password_scope).
                A repeated run finds everything in place and writes nothing.
                If a run fails after earlier steps committed, the summary says
                which steps finished; running it again resumes safely.

Output is a safe summary only: never a URL, host, password, hash or SQL.
The password is read with getpass (no default, never an argument) and held
only while the command runs; no transaction is open while it is typed or
while the optimizer runs.
"""

